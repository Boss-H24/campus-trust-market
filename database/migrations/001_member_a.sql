CREATE TABLE IF NOT EXISTS app_user (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  demo_account VARCHAR(40) UNIQUE,
  openid_hash CHAR(64) UNIQUE,
  nickname VARCHAR(30) NOT NULL,
  avatar_asset_id BIGINT UNSIGNED NULL,
  role ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'STUDENT',
  status ENUM('ACTIVE','DISABLED') NOT NULL DEFAULT 'ACTIVE',
  certification_status ENUM('UNVERIFIED','PENDING','VERIFIED','REJECTED') NOT NULL DEFAULT 'UNVERIFIED',
  credit_score INT NOT NULL DEFAULT 80 CHECK (credit_score BETWEEN 0 AND 100),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS auth_session (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES app_user(id), INDEX idx_session_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS student_roster (
  student_id_hash CHAR(64) PRIMARY KEY,
  name_hash CHAR(64) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user_certification (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL UNIQUE,
  student_id_hash CHAR(64) NOT NULL UNIQUE,
  school VARCHAR(100) NOT NULL,
  real_name_enc TEXT NOT NULL,
  student_id_enc TEXT NOT NULL,
  phone_enc TEXT NOT NULL,
  status ENUM('PENDING','VERIFIED','REJECTED') NOT NULL,
  rejection_reason VARCHAR(200) NOT NULL DEFAULT '',
  reviewed_by BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES app_user(id), FOREIGN KEY (reviewed_by) REFERENCES app_user(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS category (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(30) NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS upload_asset (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner_id BIGINT UNSIGNED NOT NULL,
  storage_key VARCHAR(100) NOT NULL UNIQUE,
  content_type VARCHAR(30) NOT NULL,
  byte_size INT UNSIGNED NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (owner_id) REFERENCES app_user(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  seller_id BIGINT UNSIGNED NOT NULL,
  category_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(50) NOT NULL,
  normalized_title VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  price_cents INT UNSIGNED NOT NULL,
  condition_label ENUM('NEW','LIKE_NEW','GOOD','FAIR') NOT NULL,
  status ENUM('PENDING','ON_SALE','REJECTED','OFF_SHELF','LOCKED','SOLD','FROZEN') NOT NULL DEFAULT 'PENDING',
  rejection_reason VARCHAR(200) NOT NULL DEFAULT '',
  version INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (seller_id) REFERENCES app_user(id), FOREIGN KEY (category_id) REFERENCES category(id),
  INDEX idx_product_search(status,category_id,price_cents,id),
  INDEX idx_product_duplicate(seller_id,normalized_title,price_cents,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_image (
  product_id BIGINT UNSIGNED NOT NULL,
  asset_id BIGINT UNSIGNED NOT NULL,
  sort_order INT NOT NULL,
  PRIMARY KEY(product_id,asset_id),
  FOREIGN KEY(product_id) REFERENCES product(id), FOREIGN KEY(asset_id) REFERENCES upload_asset(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS operation_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  actor_id BIGINT UNSIGNED NOT NULL,
  action VARCHAR(60) NOT NULL,
  target VARCHAR(80) NOT NULL,
  details JSON NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY(actor_id) REFERENCES app_user(id), INDEX idx_log_actor(actor_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
